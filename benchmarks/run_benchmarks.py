#!/usr/bin/env python3
"""Benchmarks for gdml-inspector exports (see docs/benchmarks.md).

For each scenario and export mode it reports, from a clean subprocess:

* preprocessing wall time and peak RSS of the export process,
* output bytes (files written),
* for lazy exports, the initial transfer (HTML plus the chunks the default
  layers fetch),
* with ``--browser``: time to load everything, achieved frame rate while
  animating, JS heap, and estimated GPU buffer bytes.

Scenarios are synthetic (generated by ``stress_gdml.py``, nothing committed)
and/or real detector files given with ``--gdml``. Browser numbers use whatever
WebGL the machine has; headless CI uses software rendering, which is far slower
than a GPU, so compare runs on the same machine only.

    python benchmarks/run_benchmarks.py --sizes small medium
    python benchmarks/run_benchmarks.py --gdml detector.gdml --browser --json out.json
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stress_gdml  # noqa: E402

# name -> (placements, logical volumes, layout)
SYNTHETIC = {
    "small": (2_000, 40, "flat"),
    "medium": (20_000, 100, "flat"),
    "large": (100_000, 200, "flat"),
    "nested": (20_000, 100, "nested"),
}


def _without_instancing(extra: list[str]) -> list[str]:
    result, skip = [], False
    for item in extra:
        if skip:
            skip = False
        elif item == "--instancing":
            skip = True
        else:
            result.append(item)
    return result


def export_measured(gdml: Path, out: Path, mode: str, extra: list[str]) -> dict:
    cmd = [sys.executable, "-m", "gdml_inspector"]
    if mode == "lazy":
        cmd.append("--lazy")
    # --instancing only exists for lazy exports.
    mode_extra = extra if mode == "lazy" else _without_instancing(extra)
    cmd += [str(gdml), "--out", str(out), *mode_extra]
    started = time.perf_counter()
    process = subprocess.Popen(
        cmd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True
    )
    _pid, status, usage = os.wait4(process.pid, 0)
    elapsed = time.perf_counter() - started
    stderr = process.stderr.read() if process.stderr else ""
    code = os.waitstatus_to_exitcode(status)
    if code != 0:
        raise RuntimeError(f"export failed ({mode}, exit {code}):\n{stderr}")
    rss = usage.ru_maxrss * (1 if sys.platform == "darwin" else 1024)
    return {"seconds": elapsed, "peakRssBytes": rss}


def tree_bytes(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def lazy_sizes(html: Path) -> dict:
    from gdml_inspector.lazy import read_existing_manifest

    manifest = read_existing_manifest(html)
    assets = html.parent / f"{html.stem}.assets"
    wanted = [d.lower() for d in manifest.get("defaultLoad", [])]
    initial = html.stat().st_size
    for chunk in manifest["chunks"]:
        if "all" in wanted or chunk["subsystem"].lower() in wanted:
            initial += (assets / Path(chunk["url"]).name).stat().st_size
    return {
        "chunks": len(manifest["chunks"]),
        "objects": manifest["objects"],
        "vertices": manifest["vertices"],
        "initialTransferBytes": initial,
        "placementsBytes": (assets / "placements.json").stat().st_size
        if (assets / "placements.json").exists()
        else 0,
    }


_FPS = """async () => {
  const frames = 60;
  const start = performance.now();
  for (let i = 0; i < frames; i++) {
    await new Promise(resolve => requestAnimationFrame(() => {
      yaw += 0.01;
      if (typeof requestRender === 'function') requestRender();
      resolve();
    }));
  }
  return frames / ((performance.now() - start) / 1000);
}"""


def browser_metrics(out: Path, mode: str, timeout_s: float) -> dict:
    from playwright.sync_api import sync_playwright

    from gdml_inspector.server import create_server

    server = create_server(out.parent, 0)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page(viewport={"width": 1280, "height": 800})
            started = time.perf_counter()
            page.goto(f"http://127.0.0.1:{server.server_port}/{out.name}")
            if mode == "lazy":
                page.wait_for_selector("input[data-layer-key]")
                page.click("#loadAll")
                page.wait_for_function(
                    "Object.values(states).every(s => s.loaded || s.error)",
                    timeout=timeout_s * 1000,
                )
                vertices = page.evaluate(
                    "Object.values(states).reduce((n, s) => n + (s.buffers ? s.buffers.count : 0), 0)"
                )
                page_gpu_bytes = page.evaluate("gpuBytes()")
            else:
                page.wait_for_selector(
                    "#hierarchyTree .tree-row", timeout=timeout_s * 1000
                )
                vertices = page.evaluate("positions.length / 3")
            loaded = time.perf_counter() - started
            fps = page.evaluate(_FPS)
            heap = page.evaluate(
                "performance.memory ? performance.memory.usedJSHeapSize : null"
            )
            renderer = page.evaluate(
                "(() => { const e = gl.getExtension('WEBGL_debug_renderer_info');"
                " return e ? gl.getParameter(e.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER); })()"
            )
            browser.close()
    finally:
        server.shutdown()
    result = {
        "loadSeconds": loaded,
        "fps": fps,
        "jsHeapBytes": heap,
        "loadedVertices": vertices,
        "renderer": renderer,
    }
    if mode == "lazy":
        # The viewer's own accounting: 21 bytes per vertex for baked chunks, the
        # meshes plus 53 bytes per instance for instanced ones.
        result["gpuBytesEstimate"] = page_gpu_bytes
    return result


def run_case(
    name: str,
    gdml: Path,
    modes: list[str],
    extra: list[str],
    browser: bool,
    repeat: int = 1,
    browser_timeout: float = 120,
) -> list[dict]:
    rows = []
    for mode in modes:
        with tempfile.TemporaryDirectory(prefix="gdml-bench-") as tmp:
            out = Path(tmp) / "v.html"
            row: dict = {
                "scenario": name,
                "mode": mode,
                "inputBytes": gdml.stat().st_size,
            }
            runs = [export_measured(gdml, out, mode, extra) for _ in range(repeat)]
            # Median time and highest peak RSS over the repeats; every repeat
            # rewrites the same output, which is then measured once.
            row["seconds"] = sorted(r["seconds"] for r in runs)[len(runs) // 2]
            row["peakRssBytes"] = max(r["peakRssBytes"] for r in runs)
            row["repeats"] = repeat
            row["outputBytes"] = tree_bytes(out) + (
                tree_bytes(out.parent / "v.assets")
                if (out.parent / "v.assets").exists()
                else 0
            )
            if mode == "lazy":
                row.update(lazy_sizes(out))
            if browser:
                try:
                    row.update(browser_metrics(out, mode, browser_timeout))
                except Exception as error:  # a page too big to load is a result
                    row["browserError"] = str(error).splitlines()[0][:200]
            rows.append(row)
            print(
                f"  {name} / {mode}: {row['seconds']:.1f} s, {row['peakRssBytes'] / 2**20:.0f} MiB RSS",
                flush=True,
            )
    return rows


def mib(value: float | None) -> str:
    return "-" if value is None else f"{value / 2**20:.1f}"


def markdown(rows: list[dict]) -> str:
    header = (
        "| scenario | mode | time (s) | peak RSS (MiB) | output (MiB) | initial transfer (MiB) | "
        "load (s) | fps | JS heap (MiB) | est. GPU (MiB) |\n"
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n"
    )
    lines = []
    for r in rows:
        lines.append(
            f"| {r['scenario']} | {r['mode']} | {r['seconds']:.1f} | {mib(r['peakRssBytes'])} | "
            f"{mib(r['outputBytes'])} | {mib(r.get('initialTransferBytes'))} | "
            f"{'did not load' if 'browserError' in r else '-' if 'loadSeconds' not in r else format(r['loadSeconds'], '.1f')} | "
            f"{'-' if 'fps' not in r else format(r['fps'], '.0f')} | {mib(r.get('jsHeapBytes'))} | "
            f"{mib(r.get('gpuBytesEstimate'))} |"
        )
    return header + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--sizes", nargs="*", default=["small"], choices=sorted(SYNTHETIC)
    )
    parser.add_argument(
        "--gdml", nargs="*", type=Path, default=[], help="real detector files"
    )
    parser.add_argument(
        "--modes",
        nargs="+",
        default=["standalone", "lazy"],
        choices=("standalone", "lazy"),
    )
    parser.add_argument(
        "--quality", default="medium", choices=("fast", "medium", "high")
    )
    parser.add_argument(
        "--backend",
        default="python",
        choices=("python", "pyg4ometry", "auto"),
        help="meshing backend (pyg4ometry needs the extra and gives finer meshes)",
    )
    parser.add_argument(
        "--instancing",
        default="auto",
        choices=("auto", "off", "always"),
        help="lazy exports: store repeated shapes once per chunk (see --help of --lazy)",
    )
    parser.add_argument(
        "--repeat",
        type=int,
        default=1,
        help="exports per case (median time, highest RSS)",
    )
    parser.add_argument(
        "--browser-timeout",
        type=float,
        default=120,
        help="seconds to wait for a page to load before recording a failure",
    )
    parser.add_argument(
        "--browser",
        action="store_true",
        help="also measure load time, fps, heap (needs playwright)",
    )
    parser.add_argument("--json", type=Path, help="write the raw results here")
    parser.add_argument(
        "--keep", type=Path, help="keep generated GDML files in this directory"
    )
    args = parser.parse_args(argv)

    rows: list[dict] = []
    with tempfile.TemporaryDirectory(prefix="gdml-bench-src-") as tmp:
        source_dir = args.keep or Path(tmp)
        source_dir.mkdir(parents=True, exist_ok=True)
        cases: list[tuple[str, Path]] = []
        for size in args.sizes:
            placements, logical, layout = SYNTHETIC[size]
            path = source_dir / f"stress-{size}.gdml"
            path.write_text(
                stress_gdml.build(placements, logical, layout, 50), encoding="utf-8"
            )
            cases.append(
                (
                    f"synthetic-{size} ({placements:,} placements, {logical} logical)",
                    path,
                )
            )
        cases += [(p.name, p) for p in args.gdml]
        for name, path in cases:
            # Raise the caps so the scene size, not a cap, limits the run.
            extra = [
                "--instancing",
                args.instancing,
                "--backend",
                args.backend,
                "--quality",
                args.quality,
                "--max-objects",
                "10000000",
                "--max-vertices",
                "2000000000",
            ]
            rows += run_case(
                name,
                path,
                args.modes,
                extra,
                args.browser,
                args.repeat,
                args.browser_timeout,
            )
    table = markdown(rows)
    print()
    print(f"Python {platform.python_version()} on {platform.platform()}")
    print(table)
    if args.json:
        args.json.write_text(json.dumps(rows, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
